import { Button } from '@/components/ui';
import type { AiProposal } from '@/services';
import { ProjectDialog } from '@/modules/projects/components/ProjectDialog';
import { DiffPreview } from './DiffPreview';

export interface AiPreviewDialogProps {
  open: boolean;
  proposal: AiProposal | null;
  /** True while applying (disables actions). */
  applying?: boolean;
  onClose: () => void;
  /** Confirm and apply through the editor's update path. */
  onApply: () => void;
  /** Discard and ask for a new generation. */
  onRegenerate: () => void;
  /** Apply error message, if the last apply failed. */
  applyError?: string | null;
}

/**
 * Mandatory preview step (P5).
 *
 * A generated result is NEVER written to the manuscript directly: the user sees
 * the proposal here and must explicitly choose Apply, Regenerate or Reject.
 * For replacement tasks the original and the generated text are shown side by
 * side with word-level highlighting; for continuation ("insert") tasks the text
 * to be appended is shown.
 */
export function AiPreviewDialog({
  open,
  proposal,
  applying,
  onClose,
  onApply,
  onRegenerate,
  applyError,
}: AiPreviewDialogProps) {
  if (!proposal) return null;

  const isInsert = proposal.mode === 'insert';
  const isChat = proposal.mode === 'chat';

  return (
    <ProjectDialog
      open={open}
      title={isChat ? 'AI response' : isInsert ? 'Review continuation' : 'Review changes'}
      description={`Generated by ${proposal.target.modelName} · ${proposal.target.providerName}. Review before applying.`}
      onClose={onClose}
      dismissible={!applying}
      footer={
        <>
          <Button variant="ghost" size="sm" onClick={onClose} disabled={applying}>
            {isChat ? 'Close' : 'Reject'}
          </Button>
          {!isChat ? (
            <Button variant="secondary" size="sm" onClick={onRegenerate} disabled={applying}>
              Regenerate
            </Button>
          ) : null}
          {!isChat ? (
            <Button variant="primary" size="sm" onClick={onApply} loading={applying}>
              {isInsert ? 'Insert below' : 'Apply changes'}
            </Button>
          ) : null}
        </>
      }
    >
      <div className="space-y-3">
        {isInsert ? (
          <>
            <div>
              <p className="text-subtle mb-1 text-2xs font-medium uppercase tracking-wide">
                Text to continue from
              </p>
              <div className="bg-surface-muted/60 text-muted max-h-36 overflow-y-auto rounded-md p-2 text-xs leading-6 whitespace-pre-wrap">
                {proposal.originalText ? tail(proposal.originalText, 600) : 'Empty chapter'}
              </div>
            </div>
            <div>
              <p className="text-subtle mb-1 text-2xs font-medium uppercase tracking-wide">
                Continuation to insert
              </p>
              <DiffPreview original={proposal.originalText} revised={proposal.generatedText} insertionOnly />
            </div>
          </>
        ) : (
          <>
            <div>
              <p className="text-subtle mb-1 text-2xs font-medium uppercase tracking-wide">
                Original → generated (changes highlighted)
              </p>
              <DiffPreview original={proposal.originalText} revised={proposal.generatedText} />
            </div>
            <div className="grid grid-cols-1 gap-2 sm:grid-cols-2">
              <div>
                <p className="text-subtle mb-1 text-2xs font-medium uppercase tracking-wide">Original</p>
                <div className="bg-surface-muted/60 text-muted max-h-40 overflow-y-auto rounded-md p-2 text-xs leading-6 whitespace-pre-wrap">
                  {proposal.originalText || '—'}
                </div>
              </div>
              <div>
                <p className="text-subtle mb-1 text-2xs font-medium uppercase tracking-wide">Generated</p>
                <div className="bg-success-soft/40 text-ink max-h-40 overflow-y-auto rounded-md p-2 text-xs leading-6 whitespace-pre-wrap">
                  {proposal.generatedText || '—'}
                </div>
              </div>
            </div>
          </>
        )}

        {proposal.usage?.totalTokens ? (
          <p className="text-subtle text-2xs">Tokens used: {proposal.usage.totalTokens}</p>
        ) : null}

        {applyError ? (
          <p className="text-danger text-xs" role="alert">
            {applyError}
          </p>
        ) : null}
      </div>
    </ProjectDialog>
  );
}

/** Returns the last `max` characters, prefixed with an ellipsis when truncated. */
function tail(text: string, max: number): string {
  if (text.length <= max) return text;
  return `…${text.slice(text.length - max)}`;
}
